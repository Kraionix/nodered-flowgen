/**
 * Deploy end to end: validate → plan → apply → probe → rollback, against a real instance.
 *
 * What is actually being proven here, beyond "the HTTP call returned 200":
 *
 * * **ownership** — a container the tool does not own survives the deploy byte for byte, even
 *   though `POST /flows` replaces the whole flow set;
 * * **compare-and-swap** — a stale revision is refused with 409 and the deploy re-plans instead
 *   of clobbering the other writer;
 * * **reversibility** — the receipt puts the instance back exactly as it was;
 * * **behaviour** — an endpoint defined in the generated flow answers after the deploy.
 */

