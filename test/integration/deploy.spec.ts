const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

let instance: NodeRedInstance;
let client: AdminApiClient;
let palette: Record<string, PaletteType>;

/**
 * The project source: two tabs, a subflow with typed parameters and an instance override, a
 * group, a config reference and a three-output switch — with no hand-written JSON anywhere.
 */
const definition = defineFlowSet((f) => {
  const scale = f.subflow(
    'scale',
    {
      name: 'scale × factor',
      info: 'Multiplies payload by the `factor` subflow parameter.',
      params: { factor: P.num(2), tag: P.str('default'), verbose: P.bool(true), secret: P.cred() },
      ports: { in: ['value'], out: ['scaled'] },
    },
    (s) => {
      const work = s.node('function', {
        key: 'work',
        name: 'x factor',
        func: 'const factor = env.get("factor");\nmsg.payload = msg.payload * factor;\nmsg.tag = env.get("tag");\nreturn msg;',
        outputs: 1,
      });
      s.in(work);
      s.out(work, 0);
    },
  );

  const tab = f.flow('orders', { label: 'Orders API', info: 'Generated by flowgen.' });
  const httpIn = tab.node('http in', { key: 'get_scale', url: '/flowgen/scale', method: 'get', name: 'GET /flowgen/scale' });
  const read = tab.node('function', {
    key: 'read_x',
    name: 'read ?x=',
    func: 'msg.payload = Number(msg.req.query.x ?? 1);\nreturn msg;',
    outputs: 1,
  });
  const instance = tab.instance(scale, { key: 'scale_x3', name: 'scale x3', env: { factor: 3, verbose: false } });
  const reply = tab.node('http response', { key: 'reply', statusCode: '', headers: {} });
  tab.chain(httpIn, read, instance, reply);

  const dash = dashboardIn(tab, { baseName: 'Ops' });
  const page = dash.tab('page', { name: 'KPIs' });
  const panel = dash.group('panel', page, { name: 'KPIs', width: 6 });
  dash.gauge(panel, { name: 'load', min: 0, max: 100 });

  const broker = f.config('mqtt-broker', { key: 'broker', name: 'unused broker', port: 1883, autoConnect: false });
  const publish = tab.node('mqtt out', { key: 'publish', name: 'publish', topic: 'flowgen/out', broker });
  const classify = tab.node('switch', {
    key: 'classify',
    name: 'classify',
    property: 'payload',
    outputs: 3,
    rules: [
      { t: 'eq', v: '7', vt: 'num' },
      { t: 'gt', v: '5', vt: 'num' },
    ],
  });
  classify.toPort(0, publish);
  const group = tab.group('kpi', { name: 'classifier' });
  group.add(classify);
});

before(async () => {
  instance = await startNodeRed({
    auth: 'password',
    users: [
      { username: 'flowgen', password: 's3cret', permissions: '*' },
      { username: 'reader', password: 'readonly', permissions: 'read' },
    ],
    userModules: ['node-red-dashboard'],
  });
  client = new AdminApiClient({ url: instance.url, token: await instance.token() });

  const snapshot = await filesystemSource({
    coreNodesDir: path.join(REPO_ROOT, 'node_modules', '@node-red', 'nodes'),
    userDir: REPO_ROOT,
  }).load();
  palette = { ...snapshot.types };
});

after(async () => {
  await instance?.stop();
});

/**
 * Builds the flow set, then folds its own subflow instance types into the palette used for
 * validation and emission — the same two-step the CLI performs (build, then overlay, because a
 * subflow's ports are only known once the source has been read).
 */
function buildFlowSet(): FlowSet {
  const built = definition.build({ palette });
  return built.flowSet;
}

function paletteWithSubflows(flowSet: FlowSet): Record<string, PaletteType> {
  const snapshot = {
    schemaVersion: 1,
    generator: 'flowgen',
    nodeRedVersion: null,
    contentHash: '',
    provenance: { kind: 'snapshot' as const, url: null, userDir: null, nodeModulesDirs: null },
    nodeSets: [],
    types: palette,
  };
  const overlaid = applyOverlays(snapshot, [subflowOverlay(flowSet.subflows.map(subflowDefinitionLike))]);
  return { ...overlaid.types };
}

function validate(flowSet: FlowSet) {
  return runValidators(
    defaultValidators(),
    { flowSet, palette: paletteWithSubflows(flowSet), targetVersion: null },
    { mode: 'bail', capabilities: new Set() },
  );
}

test('the authored flow set validates with no errors', async () => {
  const flowSet = buildFlowSet();
  const report = validate(flowSet);
  assert.deepEqual(
    report.problems.filter((problem) => problem.severity === 'error'),
    [],
    JSON.stringify(report.problems, null, 2),
  );
});

test('apply creates the containers, keeps a foreign tab, and the flow answers at runtime', async () => {
  const flowSet = buildFlowSet();

  // Somebody else's tab, deployed before we arrive.
  const foreign = [
    { id: 'foreign_tab', type: 'tab', label: 'Someone else', disabled: false, info: '' },
    {
      id: 'foreign_inject',
      type: 'inject',
      z: 'foreign_tab',
      name: '',
      props: [],
      repeat: '',
      crontab: '',
      once: false,
      onceDelay: 0.1,
      topic: '',
      payload: '',
      payloadType: 'str',
      x: 100,
      y: 100,
      wires: [[]],
    },
  ];
  const state = await client.readFlows();
  await client.writeFlows(foreign, state.rev);

  const current = await client.readFlows();
  const plan = planMerge({
    target: 'local',
    rev: current.rev,
    current: parseFlowFile(current.flows, { palette }),
    desired: flowSet,
    palette,
    owned: new Set(),
    ownedEntities: new Set(),
  });

  const result = await applyDeployment({
    client,
    target: 'local',
    desired: flowSet,
    palette,
    owned: new Set(),
    ownedEntities: new Set(),
    problems: validate(flowSet).problems,
    receiptPath: path.join(instance.userDir, 'receipt.json'),
  });
  assert.equal(result.applied, true, result.message);
  assert.ok(plan.operations.some((operation) => operation.id === 'foreign_tab'), 'the foreign tab was planned around');

  const readback = await client.readFlows();
  const ids = readback.flows.map((entry) => (entry as { id: string }).id);
  assert.ok(ids.includes('foreign_tab'), 'a container we do not own survives the deploy');
  assert.ok(ids.includes('orders'));
  assert.ok(ids.includes('scale'));

  const answered = await waitFor(async () => {
    const response = await fetch(`${instance.url}/flowgen/scale?x=7`);
    return response.status === 200 && (await response.text()) === '21';
  });
  assert.equal(answered, true, 'the generated flow runs: 7 × 3 through the subflow parameter');
  assert.doesNotMatch(instance.log(), /Waiting for missing types/);
});

test('a second apply is a no-op', async () => {
  const flowSet = buildFlowSet();
  const state = await client.readFlows();
  const current = parseFlowFile(state.flows, { palette });
  const plan = planMerge({
    target: 'local',
    rev: state.rev,
    current,
    desired: flowSet,
    palette,
    owned: new Set(['orders', 'scale']),
    ownedEntities: new Set(),
  });

  const changing = plan.operations.filter(
    (operation) => operation.changes.length > 0 || operation.kind.startsWith('create') || operation.kind.startsWith('delete'),
  );
  assert.equal(isNoop(plan), true, JSON.stringify(changing, null, 2));
});

test('what the server reads back is byte-identical to what we emitted, key order included', async () => {
  const flowSet = buildFlowSet();
  const paletteNow = paletteWithSubflows(flowSet);
  const payload = JSON.parse(emitFlowSet(flowSet, { palette: paletteNow })) as Record<string, unknown>[];

  const applied = await applyDeployment({
    client,
    target: 'local',
    desired: flowSet,
    palette: paletteNow,
    owned: new Set(['orders', 'scale']),
    problems: [],
  });
  assert.equal(applied.applied, true, applied.message);

  const readback = await client.readFlows();
  const byId = new Map(readback.flows.map((entry) => [(entry as { id: string }).id, entry]));
  for (const entry of payload) {
    const deployed = byId.get(String(entry['id']));
    assert.ok(deployed, `entry ${String(entry['id'])} is missing after the deploy`);
    assert.equal(
      JSON.stringify(deployed),
      JSON.stringify(entry),
      `entry ${String(entry['id'])} came back changed (key order or value)`,
    );
  }
});

test('a stale revision is refused and the caller re-plans', async () => {
  const stale = await client.readFlows();

  // Somebody else deploys in between: a real change, so the revision moves.
  await client.writeFlows(
    [...stale.flows, { id: 'foreign_comment', type: 'comment', z: 'foreign_tab', name: 'note', info: '', x: 100, y: 300, wires: [] }],
    stale.rev,
  );

  await assert.rejects(
    () => client.writeFlows(stale.flows, stale.rev),
    (error: unknown) => error instanceof AdminApiError && error.code === 'version-mismatch',
  );

  const flowSet = buildFlowSet();
  const result = await applyDeployment({
    client,
    target: 'local',
    desired: flowSet,
    palette,
    owned: new Set(['orders', 'scale']),
    problems: [],
  });
  assert.equal(result.applied, true, 'apply re-reads and re-plans instead of clobbering');
});

test('a read-scope token can plan but not apply', async () => {
  const reader = new AdminApiClient({ url: instance.url, token: await instance.token('reader') });
  await assert.rejects(
    () => reader.readFlows().then(() => reader.writeFlows([], null)),
    (error: unknown) => error instanceof AdminApiError && (error.code === 'unauthorized' || error.code === 'forbidden'),
  );
});

test('rollback restores the instance exactly as it was', async () => {
  const before = await client.readFlows();
  const beforeText = JSON.stringify(before.flows);

  const flowSet = buildFlowSet();
  const applied = await applyDeployment({
    client,
    target: 'local',
    desired: flowSet,
    palette,
    owned: new Set(['orders', 'scale']),
    problems: [],
    receiptPath: path.join(instance.userDir, 'receipt.json'),
  });
  assert.equal(applied.applied, true);
  assert.ok(applied.receipt);

  const rolled = await rollbackDeployment(client, applied.receipt as never);
  assert.equal(rolled.restored, true, rolled.message);

  const after = await client.readFlows();
  assert.equal(JSON.stringify(after.flows), beforeText, 'rollback leaves the instance byte-identical');
});
