/**
 * Type code generation: palette snapshot → per-module module augmentations.
 *
 * The output is deliberately boring TypeScript:
 *
 * ```ts
 * export {};
 * declare module '@kraionix/nodered-flowgen' {
 *   interface KnownTypes { 'inject': true }
 *   interface PaletteTypes {
 *     'inject': { name?: string; topic?: string; payload?: unknown };
 *   }
 * }
 * ```
 *
 * Optionality follows one rule, chosen so the compiler enforces what the palette *demands*
 * and nothing more: a property is required only when the palette marks it `required` **and**
 * declares no literal default — that is exactly the config-reference case (`group`, `broker`),
 * where nothing can be filled in. Properties with a declared default are optional because the
 * builder materialises the default into the emitted node.
 *
 * Value types are inferred from the declared default. Object and array samples are emitted as
 * `{ observed?: … } & Record<string, unknown>`: the sample is a lower bound on the shape, not a
 * schema, so autocompletion is offered without rejecting valid values the palette never showed.
 */

import type { PaletteProperty, PaletteType, RefTargets } from '../model.ts';
import type { PaletteSnapshot } from '../snapshot.ts';

export interface GeneratedFile {
  /** Path relative to the consumer project root, always with forward slashes. */
  readonly path: string;
  readonly content: string;
  /** Node types contained in this file, for reporting. */
  readonly types: readonly string[];
}

export interface EmitTypesOptions {
  /** Output directory; defaults to `palettes/local.d`. */
  readonly directory?: string;
  /** Module specifier to augment; defaults to this package's own name. */
  readonly packageName?: string;
  /** Include the provenance header; on by default. */
  readonly header?: boolean;
}

export const DEFAULT_TYPES_DIRECTORY = 'palettes/local.d';
export const DEFAULT_PACKAGE_NAME = '@kraionix/nodered-flowgen';

export function emitTypes(snapshot: PaletteSnapshot, options: EmitTypesOptions = {}): readonly GeneratedFile[] {
  const directory = options.directory ?? DEFAULT_TYPES_DIRECTORY;
  const packageName = options.packageName ?? DEFAULT_PACKAGE_NAME;
  const header = options.header ?? true;

  const byModule = new Map<string, PaletteType[]>();
  for (const type of Object.values(snapshot.types) as PaletteType[]) {
    const group = byModule.get(type.module);
    if (group === undefined) byModule.set(type.module, [type]);
    else group.push(type);
  }

  const files: GeneratedFile[] = [];
  const modules = [...byModule.keys()].sort();

  for (const module of modules) {
    const types = (byModule.get(module) as PaletteType[]).slice().sort((a, b) => (a.id < b.id ? -1 : 1));
    const version = types[0]?.version ?? '';
    const fileName = `${sanitize(module)}@${sanitize(version)}.d.ts`;
    files.push({
      path: `${directory}/${fileName}`,
      content: renderModuleFile({ module, version, types, packageName, header, contentHash: snapshot.contentHash }),
      types: types.map((type) => type.id),
    });
  }

  files.push({
    path: `${directory}/index.d.ts`,
    content: renderIndexFile(files.map((file) => file.path.slice(directory.length + 1)), snapshot),
    types: [],
  });

  return files;
}

function renderIndexFile(fileNames: readonly string[], snapshot: PaletteSnapshot): string {
  const lines = [
    '/**',
    ' * Generated by flowgen — do not edit.',
    ` * Palette: ${snapshot.contentHash}`,
    ' *',
    ' * Include this file (or the whole directory) from your tsconfig to activate the',
    ' * generated node types.',
    ' */',
    '',
    ...fileNames.map((name) => `/// <reference path="./${name}" />`),
    '',
  ];
  return lines.join('\n');
}

interface ModuleFileInput {
  readonly module: string;
  readonly version: string;
  readonly types: readonly PaletteType[];
  readonly packageName: string;
  readonly header: boolean;
  readonly contentHash: string;
}

function renderModuleFile(input: ModuleFileInput): string {
  const lines: string[] = [];
  if (input.header) {
    lines.push(
      '/**',
      ' * Generated by flowgen — do not edit.',
      ' *',
      ` * Module: ${input.module}@${input.version} (${input.types.length} node types)`,
      ` * Palette: ${input.contentHash}`,
      ' * Regenerate with: flowgen types gen',
      ' */',
    );
  }
  // Without a top-level import/export this file would be an ambient module declaration and
  // every augmentation inside it would be ignored.
  lines.push('export {};', '', `declare module '${input.packageName}' {`);

  lines.push('  interface KnownTypes {');
  for (const type of input.types) {
    lines.push(`    ${quote(type.id)}: true;`);
  }
  lines.push('  }', '');

  lines.push('  interface PaletteTypes {');
  for (const type of input.types) {
    lines.push(`    /** ${docFor(type)} */`);
    lines.push(`    ${quote(type.id)}: {`);
    for (const [name, property] of Object.entries(type.defaults)) {
      lines.push(`      ${quote(name)}${isRequired(property) ? '' : '?'}: ${propertyType(type, name, property)};`);
    }
    if (type.params.length > 0) {
      lines.push('      /** Subflow parameter overrides, keyed by parameter name. */');
      lines.push('      env?: {');
      for (const parameter of type.params) {
        lines.push(`        ${quote(parameter.name)}?: ${parameterType(parameter.type)};`);
      }
      lines.push('      };');
    }
    lines.push('    };');
  }
  lines.push('  }');
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

/** A property is demanded by the compiler only when nothing could be filled in for it. */
function isRequired(property: PaletteProperty): boolean {
  return property.required && property.value === undefined && !property.dynamic;
}

function propertyType(type: PaletteType, name: string, property: PaletteProperty): string {
  if (property.type !== null) return refType(type.refs[name]?.targets);
  return inferType(property.value, 0);
}

function refType(targets: RefTargets | undefined): string {
  if (targets === undefined || targets === '*') return 'Ref';
  if (targets.length === 1) return `Ref<${quote(targets[0] as string)}>`;
  return `Ref<${targets.map((target) => quote(target)).join(' | ')}>`;
}

function parameterType(type: string): string {
  switch (type) {
    case 'num':
      return 'number | string';
    case 'bool':
      return 'boolean | string';
    case 'json':
      return 'EnvValue';
    default:
      return 'EnvValue';
  }
}

/** Infers a value type from a declared default; the sample is a lower bound, not a schema. */
function inferType(value: unknown, depth: number): string {
  if (value === undefined) return 'unknown';
  if (value === null) return 'null';
  if (typeof value === 'string') return 'string';
  if (typeof value === 'number') return 'number';
  if (typeof value === 'boolean') return 'boolean';
  if (Array.isArray(value)) return arrayType(value, depth);
  if (typeof value === 'object') return objectType(value as Record<string, unknown>, depth);
  return 'unknown';
}

function arrayType(items: readonly unknown[], depth: number): string {
  if (items.length === 0) return 'unknown[]';
  if (depth > 3) return 'unknown[]';

  if (items.every(isPlainObject)) {
    const members = new Map<string, string[]>();
    for (const item of items as readonly Record<string, unknown>[]) {
      for (const [key, value] of Object.entries(item)) {
        const observed = members.get(key);
        if (observed === undefined) members.set(key, [inferType(value, depth + 1)]);
        else observed.push(inferType(value, depth + 1));
      }
    }
    return `Array<${renderMembers(members)}>`;
  }

  const element = union(items.map((item) => inferType(item, depth + 1)));
  return `Array<${element}>`;
}

function objectType(value: Record<string, unknown>, depth: number): string {
  if (depth > 3) return 'Record<string, unknown>';
  const members = new Map<string, string[]>();
  for (const [key, entry] of Object.entries(value)) {
    members.set(key, [inferType(entry, depth + 1)]);
  }
  return renderMembers(members);
}

function renderMembers(members: ReadonlyMap<string, readonly string[]>): string {
  if (members.size === 0) return 'Record<string, unknown>';
  const rendered = [...members.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([key, types]) => `${quote(key)}?: ${union(types)};`);
  // `Record<string, unknown>` keeps the door open for values the palette never sampled while
  // still offering completion for the keys it did.
  return `{ ${rendered.join(' ')} } & Record<string, unknown>`;
}

function union(types: readonly string[]): string {
  const unique = [...new Set(types)];
  if (unique.length === 1) return unique[0] as string;
  return unique.join(' | ');
}

function docFor(type: PaletteType): string {
  const parts = [`node set ${type.nodeSet}@${type.version}`];
  if (type.category !== null) parts.push(`category ${type.category}`);
  if (type.inputs !== null || type.outputs !== null) parts.push(`${type.inputs ?? 0} in / ${type.outputs ?? 0} out`);
  if (type.isConfig) parts.push('config node');
  if (type.synthetic) parts.push('no editor definition: properties are an open bag');
  const references = Object.keys(type.refs);
  if (references.length > 0) parts.push(`references: ${references.join(', ')}`);
  return sanitizeComment(parts.join(' · '));
}

function sanitizeComment(text: string): string {
  return text.replace(/\*\//g, '*\\/').replace(/[\r\n]+/g, ' ');
}

function quote(value: string): string {
  return JSON.stringify(value);
}

/** File-name-safe form of a module name (`@scope/name` → `scope-name`, `flowgen:inline` → …). */
export function sanitize(value: string): string {
  return value.replace(/^@/, '').replace(/[^A-Za-z0-9._-]+/g, '-');
}

function isPlainObject(value: unknown): boolean {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}
