/**
 * Human-readable projections of a palette.
 *
 * Two audiences, one function each:
 *
 * * `emitCheatSheet` writes a Markdown reference (one row per node type: category, ports,
 *   required properties, references) — the fastest way for an author — or an agent — to find
 *   out what `mqtt in` actually accepts without reading 900 KB of extracted HTML;
 * * `emitPaletteModule` writes the JSON module a consumer can import (for example a front-end
 *   that renders its own property editor) with the same content as the snapshot file.
 *
 * Both are pure string builders: writing files is the CLI's job.
 */

import { serializePaletteSnapshot, type PaletteSnapshot } from '../snapshot.ts';
import { isReferenceProperty, type PaletteType } from '../model.ts';

export interface CheatSheetOptions {
  /** Include the palette hash and source line; on by default. */
  readonly header?: boolean;
  /** Restrict to these npm modules. */
  readonly modules?: readonly string[];
}

export function emitCheatSheet(snapshot: PaletteSnapshot, options: CheatSheetOptions = {}): string {
  const types = Object.values(snapshot.types)
    .filter((type) => options.modules === undefined || options.modules.includes(type.module))
    .sort((a, b) => (a.module === b.module ? (a.id < b.id ? -1 : 1) : a.module < b.module ? -1 : 1));

  const lines: string[] = [];
  if (options.header ?? true) {
    lines.push(
      '# Node palette',
      '',
      `Generated by flowgen from palette \`${snapshot.contentHash}\` (${types.length} node types).`,
      snapshot.nodeRedVersion === null ? '' : `Node-RED ${snapshot.nodeRedVersion}.`,
      '',
      'Properties are shown as they are declared by the node itself; `?` marks an optional',
      'property, `→` a reference to another node type.',
      '',
    );
  }

  let currentModule = '';
  for (const type of types) {
    if (type.module !== currentModule) {
      currentModule = type.module;
      const version = type.version === '' ? '' : `@${type.version}`;
      lines.push(`## ${currentModule}${version}`, '');
    }
    lines.push(`### ${type.id}`, '', ...describeType(type), '');
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

function describeType(type: PaletteType): readonly string[] {
  const lines: string[] = [];
  const facts: string[] = [];
  if (type.isConfig) facts.push('config node');
  if (type.category !== null) facts.push(`category: ${type.category}`);
  if (type.inputs !== null || type.outputs !== null) facts.push(`ports: ${type.inputs ?? 0} in / ${type.outputs ?? 0} out`);
  if (type.synthetic) facts.push('no editor definition');
  if (facts.length > 0) lines.push(facts.join(' · '), '');

  const properties = Object.entries(type.defaults);
  if (properties.length > 0) {
    lines.push('| property | type | default | notes |', '|---|---|---|---|');
    for (const [name, property] of properties) {
      const notes: string[] = [];
      if (property.required) notes.push('required');
      if (property.dynamic) notes.push('computed in the editor');
      if (isReferenceProperty(property)) {
        const spec = type.refs[name];
        notes.push(spec === undefined ? 'reference' : `→ ${spec.targets === '*' ? 'any type' : spec.targets.join(' | ')}${spec.kind === 'many' ? ' (many)' : ''}`);
      }
      lines.push(
        `| \`${name}\` | ${propertyTypeLabel(property.value)} | ${defaultLabel(property.value)} | ${notes.join(', ')} |`,
      );
    }
    lines.push('');
  }

  if (type.params.length > 0) {
    lines.push('Subflow parameters (instance overrides live in `env`):', '');
    lines.push('| parameter | type | default |', '|---|---|---|');
    for (const parameter of type.params) {
      lines.push(`| \`${parameter.name}\` | ${parameter.type} | ${defaultLabel(parameter.value)} |`);
    }
    lines.push('');
  }

  return lines;
}

function propertyTypeLabel(value: unknown): string {
  if (value === undefined) return 'unknown';
  if (value === null) return 'null';
  if (Array.isArray(value)) return value.length === 0 ? 'unknown[]' : 'array';
  return typeof value;
}

function defaultLabel(value: unknown): string {
  if (value === undefined) return '—';
  const text = JSON.stringify(value) ?? String(value);
  return `\`${text.length > 40 ? `${text.slice(0, 37)}...` : text}\``;
}

/** The palette as a JSON module, byte-identical in content to the snapshot file. */
export function emitPaletteModule(snapshot: PaletteSnapshot, options: { readonly indent?: number } = {}): string {
  const text = serializePaletteSnapshot(snapshot, options.indent === undefined ? {} : { indent: options.indent });
  return `// Generated by flowgen — do not edit.\nexport default ${text.trimEnd()} as const;\n`;
}
