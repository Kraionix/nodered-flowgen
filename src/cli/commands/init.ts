/**
 * `flowgen init` — scaffold a project.
 *
 * It writes exactly three things and stops: a typed config, the ignore entries for the artifacts
 * that must never be committed (receipts, the extraction cache), and — with `--pull` — the first
 * palette snapshot. Nothing is overwritten without `--force`, because the config is the one file
 * in the project that is hand-written.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { DEFAULT_CONFIG_FILE } from '../../config/index.ts';

import { flag, text, type OptionSpec } from '../args.ts';
import { EXIT, UsageError } from '../exit.ts';
import { lines, type CommandResult } from '../output.ts';
import { findConfigFile } from '../project.ts';
import type { CliContext } from '../context.ts';
import type { ParsedArgs } from '../args.ts';

export const INIT_OPTIONS: readonly OptionSpec[] = [
  { name: 'profile', kind: 'string', placeholder: '<name>', description: 'palette profile to scaffold (default: local)' },
  { name: 'url', kind: 'string', placeholder: '<url>', description: 'Node-RED instance to configure as the default target' },
  { name: 'token-env', kind: 'string', placeholder: '<VAR>', description: 'environment variable holding the instance token' },
  { name: 'pull', kind: 'boolean', description: 'pull the palette snapshot right away' },
  { name: 'force', kind: 'boolean', description: 'overwrite an existing config file' },
];

export const INIT_USAGE: readonly string[] = ['init [options]'];

/** Entries every flowgen project wants ignored: runtime artifacts, never sources. */
const GITIGNORE_ENTRIES = ['.flowgen/', 'node_modules/.cache/flowgen/'];

export async function initCommand(context: CliContext, args: ParsedArgs): Promise<CommandResult> {
  const root = path.resolve(context.cwd, text(args, 'cwd') ?? '.');
  const profile = text(args, 'profile') ?? 'local';
  const url = text(args, 'url');
  const tokenEnv = text(args, 'token-env');
  const force = flag(args, 'force');

  const existing = await findConfigFile(root);
  if (existing !== null && !force) {
    throw new UsageError(
      `${path.relative(root, existing) || existing} already exists`,
      'pass --force to overwrite it, or --config <file> to scaffold elsewhere',
    );
  }

  const configFile = path.join(root, force && existing !== null ? existing : DEFAULT_CONFIG_FILE);
  await mkdir(path.dirname(configFile), { recursive: true });
  await writeFile(configFile, configTemplate({ profile, url, tokenEnv }), 'utf8');

  const ignored = await ensureGitignore(root);
  const messages = lines(
    `created ${path.relative(root, configFile) || configFile}`,
    ignored ? 'added .flowgen/ to .gitignore' : null,
    'next: `flowgen palette pull` to snapshot the palette, then `flowgen types gen`',
  );

  const data: Record<string, unknown> = {
    root,
    configFile: path.relative(root, configFile) || configFile,
    profile,
  };

  if (flag(args, 'pull')) {
    const { palettePullCommand } = await import('./palettePull.ts');
    const pulled = await palettePullCommand(context, args);
    return {
      command: 'init',
      exitCode: pulled.exitCode,
      diagnostics: pulled.diagnostics,
      messages: [...messages, ...pulled.messages],
      ...(pulled.skipped === undefined ? {} : { skipped: pulled.skipped }),
      data: { ...data, pull: pulled.data ?? {} },
    };
  }

  return { command: 'init', exitCode: EXIT.ok, diagnostics: [], messages, data };
}

interface TemplateOptions {
  readonly profile: string;
  readonly url: string | undefined;
  readonly tokenEnv: string | undefined;
}

function configTemplate(options: TemplateOptions): string {
  const profileEntry =
    options.url === undefined
      ? `{ snapshot: 'palettes/${options.profile}.json' }`
      : `{\n        url: '${options.url}',\n${options.tokenEnv === undefined ? '' : `        tokenEnv: '${options.tokenEnv}',\n`}      }`;

  const targetEntry =
    options.url === undefined
      ? ''
      : `\n  targets: {\n    local: {\n      url: '${options.url}',\n${options.tokenEnv === undefined ? '' : `      tokenEnv: '${options.tokenEnv}',\n`}      paletteProfile: '${options.profile}',\n    },\n  },`;

  return `import { defineConfig, defineFlowSet } from '@kraionix/nodered-flowgen';

export default defineConfig({
  flowSet: defineFlowSet((f) => {
    const tab = f.flow('main', { label: 'Main', info: 'Generated by flowgen.' });
    const tick = tab.node('inject', { key: 'tick', name: 'tick', repeat: '60', once: true, onceDelay: 1 });
    const show = tab.node('debug', { key: 'show', name: 'payload', complete: 'payload' });
    tab.chain(tick, show);
  }),

  palette: {
    default: '${options.profile}',
    profiles: {
      ${options.profile}: ${profileEntry},
    },
  },${targetEntry}
});
`;
}

/** Appends the ignore entries if they are not there yet; returns true when the file changed. */
async function ensureGitignore(root: string): Promise<boolean> {
  const file = path.join(root, '.gitignore');
  let existing = '';
  try {
    existing = await readFile(file, 'utf8');
  } catch {
    existing = '';
  }

  const present = new Set(existing.split('\n').map((line) => line.trim()));
  const missing = GITIGNORE_ENTRIES.filter((entry) => !present.has(entry));
  if (missing.length === 0) return false;

  const separator = existing === '' || existing.endsWith('\n') ? '' : '\n';
  await writeFile(file, `${existing}${separator}${existing === '' ? '' : '\n'}# flowgen runtime artifacts\n${missing.join('\n')}\n`, 'utf8');
  return true;
}
