/**
 * Milestone-1 acceptance flow (`recon/V1-SPEC-flowgen.md` §3), as a runnable project.
 *
 * Everything in here is authored: no JSON is written by hand anywhere. The flow set covers the
 * features the acceptance run has to prove:
 *
 * * a **subflow** with typed parameters (`P.num`, `P.str`, `P.bool`, `P.cred`), its ports
 *   declared, and an **instance override** — the runtime probe (`GET /flowgen/scale?x=7` → `21`)
 *   only answers if the override reached the deployed instance;
 * * a shared **config node** (`mqtt-broker`) referenced by a node in another container, which is
 *   what makes the emitter's "configs before tabs" ordering observable;
 * * a **three-output switch** with a partial rule list, which is what caught the wire-arity bug
 *   (the palette says `switch` has one output; the node declares three);
 * * a **group** holding one of the nodes;
 * * a **dashboard** page built with `dashboardIn`, so the example also depends on a
 *   user-installed module and therefore on a palette that includes one.
 *
 * The default target is a local instance; `FLOWGEN_TARGET_URL` and `FLOWGEN_TARGET_TOKEN`
 * override it, which is how the integration test points the same project at a disposable
 * instance without editing this file.
 */

import { dashboardIn, defineConfig, defineFlowSet, P } from '@kraionix/nodered-flowgen';

const url = process.env['FLOWGEN_TARGET_URL'] ?? 'http://127.0.0.1:1880';
const tokenEnv = 'FLOWGEN_TARGET_TOKEN';

export default defineConfig({
  flowSet: defineFlowSet((f) => {
    const scale = f.subflow(
      'scale',
      {
        name: 'scale × factor',
        info: 'Multiplies the payload by the `factor` subflow parameter.',
        params: { factor: P.num(2), tag: P.str('default'), verbose: P.bool(true), secret: P.cred() },
        ports: { in: ['value'], out: ['scaled'] },
      },
      (s) => {
        const work = s.node('function', {
          key: 'work',
          name: 'x factor',
          func: 'const factor = env.get("factor");\nmsg.payload = msg.payload * factor;\nmsg.tag = env.get("tag");\nreturn msg;',
          outputs: 1,
        });
        s.in(work);
        s.out(work, 0);
      },
    );

    const tab = f.flow('orders', { label: 'Orders API', info: 'Generated by flowgen.' });

    const httpIn = tab.node('http in', { key: 'get_scale', url: '/flowgen/scale', method: 'get', name: 'GET /flowgen/scale' });
    const read = tab.node('function', {
      key: 'read_x',
      name: 'read ?x=',
      func: 'msg.payload = Number(msg.req.query.x ?? 1);\nreturn msg;',
      outputs: 1,
    });
    const instance = tab.instance(scale, { key: 'scale_x3', name: 'scale x3', env: { factor: 3, verbose: false } });
    const reply = tab.node('http response', { key: 'reply', statusCode: '', headers: {} });
    tab.chain(httpIn, read, instance, reply);

    const broker = f.config('mqtt-broker', { key: 'broker', name: 'unused broker', port: 1883, autoConnect: false });
    const publish = tab.node('mqtt out', { key: 'publish', name: 'publish', topic: 'flowgen/out', broker });

    const classify = tab.node('switch', {
      key: 'classify',
      name: 'classify',
      property: 'payload',
      outputs: 3,
      rules: [
        { t: 'eq', v: '7', vt: 'num' },
        { t: 'gt', v: '5', vt: 'num' },
      ],
    });
    classify.toPort(0, publish);
    tab.group('kpi', { name: 'classifier' }).add(classify);

    const dash = dashboardIn(tab, { baseName: 'Ops' });
    const page = dash.tab('page', { name: 'KPIs' });
    const panel = dash.group('panel', page, { name: 'KPIs', width: 6 });
    dash.gauge(panel, { name: 'load', min: 0, max: 100 });
  }),

  palette: {
    default: 'local',
    profiles: {
      local: {
        url,
        tokenEnv,
        // Committed, and regenerated by `flowgen palette pull` + `flowgen types gen`.
        typesDirectory: 'palettes/local.d',
      },
    },
  },

  targets: {
    local: { url, tokenEnv, paletteProfile: 'local' },
  },
});
