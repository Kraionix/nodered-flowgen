/**
 * The dashboard example: a two-target project whose flow set is mostly dashboard.
 *
 * The acceptance example (`examples/acceptance/`) proves the deploy path — subflow parameters,
 * config ownership, the runtime probe. This one proves the *shape* a real project has once the
 * dashboard is the product:
 *
 * * **two pages** with an explicit `order`, because the order a reader sees is part of the
 *   artefact, not a property of the editor session;
 * * a **`ui_template`** whose body is a multi-line HTML fragment, stored verbatim — the widget the
 *   v1 review asked for, and the one whose body is easiest to mangle on the way through JSON;
 * * `ui_base` **theme and site**, which is the difference between a dashboard and a white page;
 * * a small **HTTP endpoint** on a second tab, so the deploy can be *probed* rather than merely
 *   inspected: `GET /flowgen/report` renders rows with the same function a user would write;
 * * **two targets** — `local` and a staging host that does not exist — so `flowgen plan
 *   --all-targets` is exercised by the acceptance run against one reachable and one unreachable
 *   instance. That fan-out is the reason the example has a second target at all.
 */

import { dashboardIn, defineConfig, defineFlowSet } from '@kraionix/nodered-flowgen';

const url = process.env['FLOWGEN_TARGET_URL'] ?? 'http://127.0.0.1:1880';
const tokenEnv = 'FLOWGEN_TARGET_TOKEN';

/** The template body, quoted in one place: the acceptance run asserts it arrived intact. */
const REPORT_TEMPLATE = `<table class="report">
  <tr ng-repeat="row in msg.payload">
    <td class="key">{{row[0]}}</td>
    <td class="value">{{row[1]}}</td>
  </tr>
</table>`;

export default defineConfig({
  flowSet: defineFlowSet((f) => {
    // --- the endpoint the acceptance run probes -------------------------------------------
    const api = f.flow('report_api', { label: 'Reports API', info: 'Renders the report as HTML.' });
    const request = api.node('http in', {
      key: 'report_request',
      name: 'GET /flowgen/report',
      url: '/flowgen/report',
      method: 'get',
    });
    const render = api.node('function', {
      key: 'render_report',
      name: 'render rows',
      func: [
        'const rows = [["cpu", 42], ["mem", 71]];',
        'msg.payload = rows.map(([key, value]) => `<tr><td>${key}</td><td>${value}</td></tr>`).join("");',
        'msg.headers = { "content-type": "text/html" };',
        'return msg;',
      ].join('\n'),
      outputs: 1,
    });
    const response = api.node('http response', { key: 'report_response', statusCode: '', headers: {} });
    api.chain(request, render, response);

    // --- the dashboard ---------------------------------------------------------------------
    const ui = f.flow('ops_ui', { label: 'Ops', info: 'Two pages: what is happening, and why.' });
    const dash = dashboardIn(ui, { baseName: 'Ops', site: 'Ops console', theme: 'dark' });

    const overview = dash.tab('overview', { name: 'Overview', order: 1, icon: 'dashboard' });
    const detail = dash.tab('detail', { name: 'Detail', order: 2, icon: 'list' });

    const summary = dash.group('summary', overview, { name: 'Summary', width: 6, order: 1 });
    const report = dash.group('report', detail, { name: 'Report', width: 12, order: 1 });

    dash.gauge(summary, { key: 'load', name: 'load', min: 0, max: 100, order: 1 });
    dash.text(summary, { key: 'status', name: 'status', order: 2 });
    dash.template(report, { key: 'report_table', name: 'report', format: REPORT_TEMPLATE, height: 6, order: 1 });

    // A widget with no `key` is named after its type; naming it is what keeps the id stable when
    // the display name changes.
    dash.chart(report, { key: 'history', name: 'history', order: 2, x: 0, y: 0, w: 6, h: 4 });
  }),

  palette: {
    default: 'local',
    profiles: {
      local: {
        url,
        tokenEnv,
        // Committed in a real project; regenerated by `flowgen palette pull` + `flowgen types gen`.
        typesDirectory: 'palettes/local.d',
      },
    },
  },

  targets: {
    local: { url, tokenEnv, paletteProfile: 'local' },
    // Deliberately unresolvable: `plan --all-targets` has to report a target it cannot reach
    // without giving up on the ones it can. `.invalid` is reserved by RFC 2606 and never resolves.
    staging: { url: 'http://staging.example.invalid:1880', tokenEnv, paletteProfile: 'local' },
  },
});
